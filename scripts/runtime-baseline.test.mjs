// --- Parser ------------------------------------------------------------------

test('parser strips trailing comments outside quotes', () => {
  const parsed = parseConfig([
    'name = "oddspark" # the production Worker',
    'main = "src/worker.js"',
    'compatibility_flags = ["a", "b"] # reviewed',
    '[ai] # metered',
    'remote = true # dev only',
  ].join('\n'));
  assert.equal(parsed.flat.name, 'oddspark');
  assert.deepEqual(parsed.flat.compatibility_flags, ['a', 'b']);
  assert.deepEqual(parsed.sections, ['ai']);
  assert.deepEqual(parsed.remoteSections, ['ai']);
});

test('parser keeps a # that is inside a quoted string', () => {
  const parsed = parseConfig('name = "a#b"\n');
  assert.equal(parsed.flat.name, 'a#b');
});

test('parser supports single-quoted literal strings', () => {
  const parsed = parseConfig("name = 'oddspark'\nmain = 'src/worker.js'\n");
  assert.equal(parsed.flat.name, 'oddspark');
  assert.equal(parsed.flat.main, 'src/worker.js');
});

test('parser rejects a multi-line array', () => {
  assert.throws(() => parseConfig('compatibility_flags = [\n  "a",\n]\n'), /multi-line arrays are not supported/);
});

test('parser tolerates a multi-line array inside a section and still attributes remote', () => {
  const parsed = parseConfig(
    'name = "x"\n[[migrations]]\ntag = "v2"\nnew_sqlite_classes = [\n  "A",\n  "B",\n]\n[[kv_namespaces]]\nbinding = "K"\nremote = true\n',
  );
  assert.deepEqual(parsed.sections, ['kv_namespaces', 'migrations']);
  assert.deepEqual(parsed.remoteSections, ['kv_namespaces']);
});

test('parser rejects an unterminated string', () => {
  assert.throws(() => parseTomlValue('"oddspark'), /unterminated string/);
});

test('parser rejects an unparseable value rather than guessing', () => {
  assert.throws(() => parseTomlValue('2026-07-01'), /unparseable TOML/);
});

test('parser rejects duplicate top-level keys', () => {
  assert.throws(() => parseConfig('name = "a"\nname = "b"\n'), /duplicate top-level TOML key: name/);
});

test('parser records [env.*] headers as an env section', () => {
  const parsed = parseConfig('name = "x"\n[env.staging.ai]\nbinding = "AI"\nremote = true\n');
  assert.ok(parsed.sections.includes('env'), `expected an env section, got ${parsed.sections.join(', ')}`);
  assert.deepEqual(parsed.remoteSections, ['env']);
});

test('parser detects remote = true inside a top-level inline table', () => {
  const parsed = parseConfig('name = "x"\nai = { binding = "AI", remote = true }\n');
  assert.ok(parsed.sections.includes('ai'));
  assert.deepEqual(parsed.remoteSections, ['ai']);
  assert.equal(parsed.remote, true);
});

test('parser treats a top-level inline table as declaring its section without remote', () => {
  const parsed = parseConfig('name = "x"\nai = { binding = "AI" }\n');
  assert.deepEqual(parsed.sections, ['ai']);
  assert.deepEqual(parsed.remoteSections, []);
});

test('parser detects remote = true in an inline table inside an array', () => {
  const parsed = parseConfig('name = "x"\nkv_namespaces = [{ binding = "SPARKS", id = "p", remote = true }]\n');
  assert.ok(parsed.sections.includes('kv_namespaces'));
  assert.deepEqual(parsed.remoteSections, ['kv_namespaces']);
});

test('parser does not mistake a remote-ish key for remote = true', () => {
  const parsed = parseConfig('name = "x"\n[ai]\nremote_hint = true\nnot_remote = true\n');
  assert.deepEqual(parsed.remoteSections, []);
});

test('parser records dotted top-level keys as their section and attributes remote', () => {
  const parsed = parseConfig('name = "x"\nai.binding = "AI"\nai.remote = true\n');
  assert.deepEqual(parsed.sections, ['ai']);
  assert.deepEqual(parsed.remoteSections, ['ai']);
  const noRemote = parseConfig('name = "x"\nai.binding = "AI"\n');
  assert.deepEqual(noRemote.sections, ['ai']);
  assert.deepEqual(noRemote.remoteSections, []);
});

test('parser records top-level route/routes keys as a routes section', () => {
  assert.deepEqual(parseConfig('name = "x"\nroute = "a.dev/*"\n').sections, ['routes']);
  assert.deepEqual(parseConfig('name = "x"\nroutes = ["a.dev/*"]\n').sections, ['routes']);
});

