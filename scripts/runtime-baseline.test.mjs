const temps = [];

function makeRepo(overrides = {}) {
  const root = mkdtempSync(join(tmpdir(), 'oddspark-baseline-test-'));
  temps.push(root);
  for (const [rel, content] of Object.entries({ ...FILES, ...overrides })) {
    const path = join(root, rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  // Fully hermetic: no signing, no hooks, no identity from the developer's
  // global config, and GIT_CEILING_DIRECTORIES so an outer repository (this one)
  // cannot be discovered if `git init` were ever to fail.
  const git = (...args) =>
    run('git', ['-c', 'commit.gpgsign=false', '-c', 'user.name=t', '-c', 'user.email=t@example.invalid', ...args], {
      cwd: root,
      stdio: 'pipe',
      env: { ...process.env, GIT_CEILING_DIRECTORIES: tmpdir(), GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null' },
    });
  git('init', '-q');
  git('add', '-A');
  git('commit', '-qm', 'fixture', '--no-verify');
  return root;
}

/** Fixture repo with a frozen baseline already in place. */
function frozenRepo(overrides = {}) {
  const root = makeRepo(overrides);
  freeze(root);
  return root;
}

