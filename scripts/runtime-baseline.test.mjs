// --- Matrix row: freeze ------------------------------------------------------

test('freeze writes deterministic, sorted, 2-space JSON with a trailing newline', () => {
  const root = makeRepo();
  const record = freeze(root);
  const text = readFileSync(join(root, BASELINE_FILE), 'utf8');
  assert.ok(text.endsWith('}\n'));
  assert.equal(text, `${JSON.stringify(JSON.parse(text), null, 2)}\n`);

  const keys = Object.keys(JSON.parse(text));
  assert.deepEqual(keys, [...keys].sort());

  const commit = run('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  assert.equal(record.frozen_from_commit, commit);
  assert.equal(record.base_commit, commit);
  assert.match(record.source_state, /uncommitted worktree/);

  // Refreezing an unchanged tree changes nothing but the timestamp.
  const second = freeze(root);
  assert.equal(second.runtime_identity_sha256, record.runtime_identity_sha256);
  const stripped = (o) => JSON.stringify({ ...o, frozen_at: null });
  assert.equal(stripped(second), stripped(record));
});

test('freeze fails when a hashed file is missing', () => {
  const root = makeRepo();
  rmSync(join(root, 'worker-configuration.d.ts'));
  assert.throws(() => freeze(root), /missing required file: worker-configuration\.d\.ts/);
});

